"""One-shot route 1 build: CADL with an embedded Allo kernel -> Chipyard-ready RTL.

    <out>/hls/            HLS project (kernel module, kernel.cpp, run.tcl, blackboxes, csynth)
    <out>/rtl/            HLS Verilog used by the wrapper (repaired Vitis output, or --rtl)
    <out>/main.sv         generated ISAX wrapper
    <out>/rtl.f, aps_config.yaml   file list and Chipyard APS config
    <out>/encoding.json   instruction encodings (tools/aps-frontend encoding)
    <out>/manifest.json   kernel ports, float lowering, SPM layout, RTL provenance
"""
from __future__ import annotations

import importlib.util
import json
import os
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

from .. import cadl_ast as ast
from ..allo import check_source
from .hls import HLSProject, emit_project, run_csynth
from .instantiate import classify, load_rtl_ports
from .main import generate_main
from .spm import build_layout

ROOT = Path(__file__).resolve().parents[2]


@dataclass
class BuildResult:
    output: Path
    hls: HLSProject
    main_sv: Path | None  # None when synthesis was skipped and no RTL was given


def load_schedule(kernel: ast.AlloKernel, directory: Path, cadl: Path):
    """Import the embedded Allo code and return its schedule object.

    Allo reads kernel source through `inspect`, so the code must live in a
    file. Leading blank lines keep its line numbers equal to the .cadl file.
    """
    module_path = directory / f"{kernel.name}_kernel.py"
    padding = "\n" * (kernel.source.span.line - 1)
    module_path.write_text(f"# From {cadl}" + padding + kernel.source.text + "\n")
    spec = importlib.util.spec_from_file_location(f"cadl_allo_{kernel.name}", module_path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    schedule = getattr(module, kernel.schedule, None)
    if schedule is None:
        raise ValueError(f"{cadl}: allo {kernel.name} names schedule '{kernel.schedule}', "
                         "which the embedded code does not define")
    if schedule.top_func_name != kernel.name:
        raise ValueError(f"{cadl}: schedule '{kernel.schedule}' customizes "
                         f"{schedule.top_func_name}, not {kernel.name}")
    return schedule


def build(cadl: Path, output: Path, *, rtl: Path | None = None, csynth: bool = True,
          vitis_hls: str = "vitis_hls") -> BuildResult:
    cadl, output = Path(cadl).resolve(), Path(output).resolve()
    proc = check_source(cadl.read_text(), str(cadl))
    if len(proc.allo_kernels) != 1:
        raise NotImplementedError(f"{cadl}: exactly one allo kernel is supported, "
                                  f"found {len(proc.allo_kernels)}")
    kernel = next(iter(proc.allo_kernels.values()))
    output.mkdir(parents=True, exist_ok=True)
    hls_dir = output / "hls"
    hls_dir.mkdir(exist_ok=True)

    project = emit_project(load_schedule(kernel, hls_dir, cadl), hls_dir)
    if rtl is not None:
        rtl_source, provenance = Path(rtl).resolve(), "given"
    elif csynth:
        if shutil.which(vitis_hls) is None:
            raise FileNotFoundError(f"{vitis_hls} not on PATH; source the Vitis settings64.sh, "
                                    "pass --rtl, or use --no-csynth")
        rtl_source, provenance = run_csynth(project, vitis_hls), "vitis_hls + rtl_fixups"
    else:
        return BuildResult(output, project, None)

    rtl_dir = output / "rtl"
    if rtl_dir.resolve() != rtl_source:
        shutil.rmtree(rtl_dir, ignore_errors=True)
        shutil.copytree(rtl_source, rtl_dir)
    instance = classify(kernel.name, load_rtl_ports(rtl_dir / f"{kernel.name}.v"), project.params)
    main_sv = output / "main.sv"
    main_sv.write_text(f"// Generated by tools/allo-gen from {cadl.name}\n"
                       + generate_main(proc, instance))

    files = [main_sv] + sorted(rtl_dir.glob("*.v")) + sorted(rtl_dir.glob("*.sv"))
    (output / "rtl.f").write_text("\n".join(map(str, files)) + "\n")
    config = dict(backend="rocc", arch="rv32", core_count=1, top_module="aps_rocc_wrapper",
                  name="aps_rocc_module", vsrc=list(map(str, files)), maxBurstBytes=128, nXacts=2)
    (output / "aps_config.yaml").write_text(json.dumps(config, indent=2) + "\n")
    env = dict(os.environ, PYTHONPATH=os.pathsep.join(
        filter(None, [str(ROOT), os.environ.get("PYTHONPATH")])))
    subprocess.run([sys.executable, str(ROOT / "tools/aps-frontend"), "encoding", str(cadl),
                    "-o", str(output / "encoding.json")], check=True, env=env)

    layout = build_layout(proc)
    manifest = {
        "source": str(cadl),
        "kernel": kernel.name,
        "params": [{"name": p.name, "interface": p.kind} for p in project.params],
        "float_calls": project.float_calls,
        "spm": [{"name": s.name, "elements": s.elements, "elem_bits": s.elem_bits,
                 "dma_base": f"0x{layout.base(s.name):x}"} for s in layout.spms],
        "rtl": {"source": str(rtl_source), "provenance": provenance},
    }
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return BuildResult(output, project, main_sv)
