"""Stage a Chipyard APSRocketConfig run of the generated GEMM ISAX.

    python examples/allo_sv_gen/package_soc.py [--rtl DIR] [--output build/gemm_soc_gen]
    pixi run bash build/gemm_soc_gen/run_soc.sh

The wrapper is generated from examples/allo/gemm.cadl; the software,
run_soc.sh and checks are those of examples/allo_manual.
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANUAL = ROOT / "examples/allo_manual"
sys.path.insert(0, str(ROOT))

from cadl_frontend.allo_sv_gen.instantiate import KernelParam, classify, load_rtl_ports  # noqa: E402
from cadl_frontend.allo_sv_gen.main import generate_main  # noqa: E402
from cadl_frontend.parser import parse_proc  # noqa: E402

PARAMS = [KernelParam("A", "ap_memory"), KernelParam("BT", "ap_memory"),
          KernelParam("C", "ap_memory"), KernelParam("use_c", "ap_none"),
          KernelParam("D", "ap_memory")]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--rtl", type=Path, default=MANUAL / "rtl")
    parser.add_argument("--output", type=Path, default=ROOT / "build/gemm_soc_gen")
    args = parser.parse_args()
    out = args.output.resolve()
    if out.parent.parent != ROOT:
        sys.exit("run_soc.sh finds the repository two levels above its directory")
    out.mkdir(parents=True, exist_ok=True)
    shutil.copy(MANUAL / "run_soc.sh", out)
    shutil.copytree(MANUAL / "software", out / "software", dirs_exist_ok=True)
    rtl = out / "rtl"
    shutil.rmtree(rtl, ignore_errors=True)
    shutil.copytree(args.rtl.resolve(), rtl)
    instance = classify("gemm_fp32", load_rtl_ports(rtl / "gemm_fp32.v"), PARAMS)
    proc = parse_proc((ROOT / "examples/allo/gemm.cadl").read_text())
    (out / "main.sv").write_text("// Generated by cadl_frontend.allo_sv_gen from examples/allo/gemm.cadl\n"
                                 + generate_main(proc, instance))
    files = [out / "main.sv"] + sorted(rtl.glob("*.v")) + sorted(rtl.glob("*.sv"))
    (out / "rtl.f").write_text("\n".join(map(str, files)) + "\n")
    config = dict(backend="rocc", arch="rv32", core_count=1, top_module="aps_rocc_wrapper",
                  name="aps_rocc_module", vsrc=list(map(str, files)), maxBurstBytes=128, nXacts=2)
    (out / "aps_config.yaml").write_text(json.dumps(config, indent=2) + "\n")
    print(f"Staged {out} with {len(files)} RTL files from {args.rtl}")


if __name__ == "__main__":
    main()
