"""Port a vla_testbench compact_accelerator.cadl to route 1.

Everything outside the `// core: begin ... // core: end` block of the run
instruction is copied verbatim; the block becomes an `invoke` of the engine
(engine_run in 02_CADL硬件/*_engine.cadl) written as an Allo kernel. The Allo block goes
after the statics.

usage: python3 port.py ORIGINAL.cadl KERNEL.allo INVOKE.cadl HEADER.txt OUT.cadl
"""
import hashlib
import re
import sys
from pathlib import Path

orig, kernel, invoke, header, out = map(Path, sys.argv[1:])
src = orig.read_text()
core = re.compile(r"\n[ \t]*// core: begin\n.*?\n[ \t]*// core: end\n", re.S)
assert len(core.findall(src)) == 1
body = core.sub("\n" + invoke.read_text().rstrip("\n") + "\n", src)

lines = body.split("\n")
assert lines[0].startswith("// ") and "Generated by accelerate/compose.py" in lines[0]
# Drop the original's three header comment lines; keep statics, then the kernel.
while lines and lines[0].startswith("//"):
    lines.pop(0)
last_static = max(i for i, l in enumerate(lines) if l.startswith("static "))
digest = hashlib.sha256(orig.read_bytes()).hexdigest()
text = (header.read_text().replace("@SHA256@", digest).rstrip("\n") + "\n"
        + "\n".join(lines[:last_static + 1]) + "\n\n"
        + kernel.read_text().rstrip("\n") + "\n\n"
        + "\n".join(lines[last_static + 1:]).lstrip("\n"))
out.write_text(text)
